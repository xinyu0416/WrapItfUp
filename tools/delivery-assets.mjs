import { readFile, writeFile } from 'node:fs/promises';
import { deflateSync } from 'node:zlib';
const root = new URL('../', import.meta.url);
const source = file => readFile(new URL('tools/delivery/' + file, root), 'utf8');
const runner = await source('run_wiu.py');
const receiver = await source('receive_wiu.py');
const assets = {runner, receiver, receiverZlib64: deflateSync(receiver, {level:9}).toString('base64')};
const script = '// Generated by tools/delivery-assets.mjs from tools/delivery/*.py.\n' +
  '(function(r){const a=' + JSON.stringify(assets) +
  ';if(typeof module!=="undefined")module.exports=a;r.WIUDeliveryAssets=a;})(globalThis);\n';
await writeFile(new URL('src/delivery-assets.js', root), script);
